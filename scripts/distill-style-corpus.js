#!/usr/bin/env node
'use strict';
// Distills the PC corpus mine (mine-full.json) into src/style-corpus.js: the
// per-style pattern pools the composer samples from. Run manually after a
// re-mine: node scripts/distill-style-corpus.js <mine.json>
const fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: distill-style-corpus.js <mine.json>'); process.exit(1); }
const d = JSON.parse(fs.readFileSync(src, 'utf8'));
const out = {};
for (const [bucket, v] of Object.entries(d)) {
  out[bucket] = {
    n: v.n,
    bpm: v.bpm,
    swing: v.swing,
    // joint kits keep kick/snare/hat coherent. Kick AND snare are required:
    // the product's smoke contract expects a backbone from every kit, and a
    // mined snare-less bar (common in VGM) fails it.
    kits: (v.kits || []).filter(k => k[0][0] && k[0][1]).slice(0, 12),
    bass: (v.bass || []).slice(0, 10),
    // "0,0,0" is static harmony; real for VGM but only styles that WANT static
    // harmony should draw it, so it is stored but flagged first
    progs: (v.progs || []).slice(0, 8)
  };
}
const js = '// GENERATED by scripts/distill-style-corpus.js from the PC MIDI corpus mine.\n' +
  '// ' + Object.entries(out).map(([k, v]) => k + ':' + v.n).join(' ') + '\n' +
  '(function (G) {\n  G.CT_STYLE_CORPUS = ' + JSON.stringify(out) + ';\n' +
  '  if (typeof module !== "undefined" && module.exports) module.exports = G.CT_STYLE_CORPUS;\n' +
  '})(typeof globalThis !== "undefined" ? globalThis : window);\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'style-corpus.js'), js);
console.log('src/style-corpus.js:', js.length, 'bytes,', Object.keys(out).length, 'buckets');

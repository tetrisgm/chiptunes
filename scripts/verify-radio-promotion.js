'use strict';
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.join(__dirname, '..');
require('child_process').execFileSync(process.execPath, ['build.js'], {cwd:root, stdio:'inherit'});
const radio = fs.readFileSync(path.join(root, 'dist/radio/index.html'), 'utf8');
const m3u = fs.readFileSync(path.join(root, 'dist/listen.m3u'), 'utf8');
const pls = fs.readFileSync(path.join(root, 'dist/listen.pls'), 'utf8');
const headers = fs.readFileSync(path.join(root, 'dist/_headers'), 'utf8');
assert.match(radio, /Take CHIPTUNES\.APP with you/);
for (const label of ['Play here','Open in radio app','Copy stream URL','Add to Broadcasts','Other players']) assert.ok(radio.includes(label), label);
assert.ok(radio.includes('https://radio.chiptunes.app'));
assert.ok(radio.includes('radio-qr.png'));
assert.strictEqual(m3u, '#EXTM3U\n#EXTINF:-1,CHIPTUNES.APP - Endless Game Boy Radio\nhttps://radio.chiptunes.app\n');
assert.match(pls, /File1=https:\/\/radio\.chiptunes\.app/);
assert.match(pls, /Title1=CHIPTUNES\.APP - Endless Game Boy Radio/);
assert.match(headers, /\/listen\.m3u[\s\S]*audio\/x-mpegurl; charset=utf-8/);
assert.match(headers, /\/listen\.pls[\s\S]*audio\/x-scpls/);
assert.ok(fs.existsSync(path.join(root, 'dist/radio-qr.png')));
console.log('verify-radio-promotion: listen-anywhere routes and metadata are complete');
